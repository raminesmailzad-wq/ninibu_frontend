import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = path.join(root, 'apps/mobile/assets/fonts');
const out = path.join(root, 'apps/mobile/src/theme/generated-font.ts');
const files = {
  regular: 'YekanBakhFaNum-Regular.ttf',
  medium: 'YekanBakhFaNum-Medium.ttf',
  bold: 'YekanBakhFaNum-Bold.ttf',
};

const exists = Object.fromEntries(
  Object.entries(files).map(([key, name]) => [key, fs.existsSync(path.join(fontDir, name))]),
);
const hasAny = Object.values(exists).some(Boolean);
const hasCore = Boolean(exists.regular && exists.bold);

const lines = [
  '// Auto-generated by scripts/mobile-font-prepare.mjs',
  '// Medium is optional: when it is not present, typography.medium uses the Regular FaNum family.',
  `export const HAS_YEKANBAKH_FANUM = ${hasCore ? 'true' : 'false'} as const;`,
  `export const HAS_YEKANBAKH_FANUM_MEDIUM = ${exists.medium ? 'true' : 'false'} as const;`,
  'export const NINIBU_FONT_ASSETS = {',
];
if (exists.regular) lines.push(`  YekanBakhFaNum: require('../../assets/fonts/${files.regular}'),`);
if (exists.medium) lines.push(`  YekanBakhFaNumMedium: require('../../assets/fonts/${files.medium}'),`);
if (exists.bold) lines.push(`  YekanBakhFaNumBold: require('../../assets/fonts/${files.bold}'),`);
lines.push('} as const;');
lines.push(
  `export const NINIBU_FONT_FAMILY = { regular: ${exists.regular ? "'YekanBakhFaNum'" : 'undefined'}, medium: ${exists.medium ? "'YekanBakhFaNumMedium'" : exists.regular ? "'YekanBakhFaNum'" : 'undefined'}, bold: ${exists.bold ? "'YekanBakhFaNumBold'" : exists.regular ? "'YekanBakhFaNum'" : 'undefined'} } as const;`,
  '',
);
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));

if (hasCore && exists.medium) {
  console.log('[mobile-font] YekanBakh FaNum Regular, Medium and Bold detected.');
} else if (hasCore) {
  console.log('[mobile-font] YekanBakh FaNum Regular and Bold detected; Medium will safely fall back to Regular.');
} else if (hasAny) {
  console.warn('[mobile-font] incomplete YekanBakh FaNum core assets; Regular and Bold are required for APK.');
} else {
  console.warn('[mobile-font] YekanBakh FaNum assets not found; Expo Go can use fallback fonts but APK readiness will fail.');
}
